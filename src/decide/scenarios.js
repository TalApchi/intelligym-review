// "Tactical choice" scenarios.
//
// ⚠ PROVISIONAL. Every scenario below is a DRAFT written by the build team, not by a coach.
// The positions, the option list, each option's rank, each sentence and the reasoning must
// be checked and signed off by Omri (or a qualified coach) before the game goes public.
// Set `approved: true` only after that sign-off. Unapproved scenarios show a "Draft scenario"
// badge and "(provisional)" verdicts, and the production build (src/build.js) leaves them out.
// Omri reviews them on review.html, which draws every scenario and option; no need to read this file.
//
// Coordinates are metres on the attacking half: y = 0 is the opponents' goal line at the
// top, y = 52.5 is halfway. Our team attacks up the screen. Roles are named from each team's
// own point of view, so "their left back" stands on the right of the screen.
//
// Scenario fields:
//   title      a few words, shown in the game and on the review page
//   carrier    id of our player on the ball (you)
//   home/away  players: [id, role, x, y]
//   cues       arrows drawn on the frozen picture: runs already under way, or pressure coming
//   reasoning  why the draft ranks the options the way it does (PROVISIONAL)
//   open       when the picture doesn't settle it: why more than one option scores 100
//   question   what we still need Omri to decide about this scenario (review page and
//              docs/tactical-rankings.md only; players never see it)
//   tags       what the situation is about, for the review page
// Option fields:
//   label      what the button says
//   score      100 | 75 | 50 | 25   (PROVISIONAL; shown to players as top / good / fair / riskier
//              option (draft)). Ties are allowed when options are equally defensible. Scores are
//              judged from the picture: pressure, the lane, the receiver's space, support, keeping
//              the ball and the chance it creates, never from whether the ball goes forward or back)
//   note       one sentence shown after the choice (PROVISIONAL)
//   result     two or three words shown as the outcome, e.g. "Cut out"
//   ball       the ball's path after the choice; the first point is the carrier
//   lofted     true if the ball goes through the air
//   moves      players who move during the outcome: { id: [x, y] }

const P = ([id, role, x, y]) => ({ id, role, x, y });
const pt = ([x, y]) => ({ x, y });

function scenario(s) {
  return {
    approved: false,
    ...s,
    home: s.home.map(P),
    away: s.away.map(P),
    cues: (s.cues || []).map(([id, x, y]) => ({ id, to: { x, y } })),
    options: s.options.map((o) => ({
      ...o,
      ball: o.ball.map(pt),
      moves: Object.fromEntries(Object.entries(o.moves || {}).map(([id, q]) => [id, pt(q)])),
    })),
  };
}

